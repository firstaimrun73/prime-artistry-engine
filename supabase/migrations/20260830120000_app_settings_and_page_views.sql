-- ── public.page_views (first-party traffic) ─────────────────────────────────
CREATE TABLE IF NOT EXISTS public.page_views (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id text NOT NULL,
  user_id uuid NULL,
  pathname text NOT NULL,
  referrer text NULL,
  device_class text NULL,
  country text NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS page_views_created_at_idx ON public.page_views (created_at DESC);
CREATE INDEX IF NOT EXISTS page_views_session_id_idx ON public.page_views (session_id);
CREATE INDEX IF NOT EXISTS page_views_pathname_idx ON public.page_views (pathname);

GRANT INSERT ON public.page_views TO anon;
GRANT INSERT ON public.page_views TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.page_views TO service_role;
-- sequence grants for identity insert
GRANT USAGE, SELECT ON SEQUENCE public.page_views_id_seq TO anon, authenticated, service_role;

ALTER TABLE public.page_views ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Anyone can insert page views" ON public.page_views;
CREATE POLICY "Anyone can insert page views" ON public.page_views
  FOR INSERT TO anon, authenticated
  WITH CHECK (true);

-- No SELECT policy for anon/authenticated — traffic aggregates only via service_role admin functions.

