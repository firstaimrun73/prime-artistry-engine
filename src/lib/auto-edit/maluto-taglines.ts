const KEY = "motio2edit.maluto.lastTaglineIdx";
export function pickMalutoTagline(): string {
  const n = MALUTO_TAGLINES.length;
  if (!n) return "Every photograph has a story worth saving.";
  let last = -1;
  try {
    const r = sessionStorage.getItem(KEY);
    if (r != null) last = Number(r);
  } catch {}
  let idx = Math.floor(Math.random() * n);
  if (n > 1 && idx === last) idx = (idx + 1) % n;
  try {
    sessionStorage.setItem(KEY, String(idx));
  } catch {}
  return MALUTO_TAGLINES[idx]!;
}
